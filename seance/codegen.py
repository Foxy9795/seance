"""Generate the Python record layer (parse/format) from the program's record layouts."""

from __future__ import annotations

from pathlib import Path

from .copybook import Layout
from .model import ROOT, load_model


def _class_source(cls_name: str, layout: Layout) -> str:
    lines = ["@dataclass", f"class {cls_name}:"]
    for f in layout.fields:
        lines.append(f"    {f.py_name}: {'str' if f.kind == 'alpha' else 'Decimal'}")
    lines += ["", "    @classmethod", f'    def parse(cls, line: str) -> "{cls_name}":', f"        line = line.ljust({layout.width})", "        return cls("]
    for f, a, b in layout.slices():
        if f.kind == "alpha":
            lines.append(f"            {f.py_name}=line[{a}:{b}].rstrip(),")
        elif f.kind == "edited":
            lines.append(f"            {f.py_name}=deedit(line[{a}:{b}]),")
        else:
            lines.append(f"            {f.py_name}=parse_numeric(line[{a}:{b}], {f.digits}, {f.scale}, {f.signed}, {f.sign!r}),")
    lines += ["        )", "", "    def format(self) -> str:", "        return (", ]
    parts = []
    for f in layout.fields:
        if f.kind == "alpha":
            parts.append(f"format_alpha(self.{f.py_name}, {f.width})")
        elif f.kind == "edited":
            parts.append(f"format_edited(self.{f.py_name}, {f.pic!r}).ljust({f.width})[:{f.width}]")
        else:
            parts.append(f"format_numeric(self.{f.py_name}, {f.digits}, {f.scale}, {f.signed}, {f.sign!r})")
    lines.append("            " + "\n            + ".join(parts))
    lines += ["        ).rstrip()", ""]
    return "\n".join(lines)


def generate_records_module(program: str, root: Path = ROOT) -> Path:
    model = load_model(program, root)
    in_layout, out_layout = model.in_layout, model.out_layout
    text = "\n".join(
        [
            f'"""Record layouts for {program}. Generated by Séance from the COBOL record descriptions. Do not edit."""',
            "",
            "from __future__ import annotations",
            "",
            "from dataclasses import dataclass",
            "from decimal import Decimal",
            "",
            "from seance.cobol_num import deedit, format_alpha, format_edited, format_numeric, parse_numeric",
            "",
            f"IN_WIDTH = {in_layout.width}",
            f"OUT_WIDTH = {out_layout.width}",
            "",
            "",
            _class_source("InRecord", in_layout),
            "",
            _class_source("OutRecord", out_layout),
        ]
    )
    target = root / "generated" / f"{program}_records.py"
    target.parent.mkdir(parents=True, exist_ok=True)
    (target.parent / "__init__.py").touch()
    target.write_text(text + "\n", encoding="utf-8")
    return target
